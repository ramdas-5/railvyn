import Link from "next/link";
import type { Metadata } from "next";
import { ArrowRight, Ticket, TrainFront } from "lucide-react";
import { requireUserPage } from "@/lib/page-auth";
import { listUserBookings } from "@/lib/domain/reservations";
import { formatDate, formatTime, msRemaining } from "@/lib/datetime";
import { formatInr, STATUS_LABELS, TRAVEL_CLASS_LABELS } from "@/lib/utils";
import { Badge, EmptyState, Panel } from "@/components/ui/surfaces";
import { Button } from "@/components/ui/button";
import { PageHeading } from "@/components/layout/page-heading";

export const metadata: Metadata = { title: "My bookings" };
export const dynamic = "force-dynamic";

export default async function MyBookingsPage() {
  const user = await requireUserPage("/my-bookings");
  const bookings = await listUserBookings(user.id);
  const upcoming = bookings.filter(
    (booking) =>
      booking.status === "confirmed" && msRemaining(booking.departureAt) > 0,
  );
  const past = bookings.filter(
    (booking) =>
      booking.status === "confirmed" && msRemaining(booking.departureAt) <= 0,
  );
  const cancelled = bookings.filter((booking) => booking.status === "cancelled");

  const sections = [
    { title: "Upcoming", items: upcoming, empty: "No upcoming journeys." },
    { title: "Past", items: past, empty: "No completed journeys in this demo." },
    { title: "Cancelled", items: cancelled, empty: "No cancelled bookings." },
  ];

  return (
    <div className="space-y-6">
      <PageHeading
        eyebrow="Passenger"
        title="My bookings"
        description="Every reference here was generated by RAILVYN. None is an official PNR or railway ticket."
        actions={
          <Button asChild>
            <Link href="/search">
              <TrainFront aria-hidden="true" className="h-4 w-4" />
              Book another journey
            </Link>
          </Button>
        }
      />

      {bookings.length === 0 ? (
        <Panel className="p-6">
          <EmptyState
            title="No bookings yet"
            description="Search a dated run, choose a leg and hold a seat. Confirmed demo bookings will appear here."
            icon={<Ticket className="h-5 w-5" />}
            action={
              <Button asChild size="sm">
                <Link href="/search">Search trains</Link>
              </Button>
            }
          />
        </Panel>
      ) : (
        <div className="space-y-6">
          {sections.map((section) => (
            <section key={section.title} aria-labelledby={`section-${section.title}`}>
              <div className="flex items-center justify-between gap-2">
                <h2 id={`section-${section.title}`} className="text-sm font-semibold uppercase tracking-[0.08em] text-fg-muted">
                  {section.title}
                  <span className="ml-2 rounded-full border border-line px-2 py-0.5 text-[10px]">
                    {section.items.length}
                  </span>
                </h2>
              </div>
              {section.items.length === 0 ? (
                <p className="mt-2 rounded-small border border-dashed border-line p-4 text-sm text-fg-muted">
                  {section.empty}
                </p>
              ) : (
                <ul className="mt-3 space-y-3">
                  {section.items.map((booking) => (
                    <li key={booking.id}>
                      <Panel className="p-4 sm:p-5">
                        <div className="flex flex-wrap items-start justify-between gap-3">
                          <div className="min-w-0">
                            <div className="flex flex-wrap items-center gap-2">
                              <Badge
                                tone={booking.status === "confirmed" ? "success" : "danger"}
                                dot
                              >
                                {STATUS_LABELS[booking.status]}
                              </Badge>
                              <span className="rv-mono text-xs font-semibold">
                                {booking.reference}
                              </span>
                              <span className="text-xs text-ink-muted">
                                {TRAVEL_CLASS_LABELS[booking.travelClass]}
                              </span>
                            </div>
                            <p className="mt-2 text-lg font-semibold">
                              {booking.fromCode} → {booking.toCode}
                            </p>
                            <p className="text-sm text-ink-muted">
                              {booking.trainCode} · {booking.trainName} ·{" "}
                              {formatDate(booking.departureAt)} ·{" "}
                              {formatTime(booking.departureAt)}
                            </p>
                            <p className="mt-1 text-xs text-ink-muted">
                              {booking.seatLabels || "Seats released"} ·{" "}
                              {booking.passengerCount} passenger
                              {booking.passengerCount === 1 ? "" : "s"} ·{" "}
                              {formatInr(booking.totalFarePaise)}
                            </p>
                          </div>
                          <div className="flex flex-wrap items-center gap-2">
                            <Button asChild size="sm" variant="outline">
                              <Link href={`/my-bookings/${booking.id}`}>
                                View ticket
                                <ArrowRight aria-hidden="true" className="h-3.5 w-3.5" />
                              </Link>
                            </Button>
                            {booking.status === "confirmed" &&
                            msRemaining(booking.departureAt) > 0 ? (
                              <Button asChild size="sm" variant="ghost-light">
                                <Link href={`/my-bookings/${booking.id}/cancel`}>Cancel</Link>
                              </Button>
                            ) : null}
                          </div>
                        </div>
                      </Panel>
                    </li>
                  ))}
                </ul>
              )}
            </section>
          ))}
        </div>
      )}
    </div>
  );
}
