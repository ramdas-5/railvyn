import Link from "next/link";
import { redirect } from "next/navigation";
import type { Metadata } from "next";
import { eq } from "drizzle-orm";
import { CheckCircle2, Download, Ticket } from "lucide-react";
import { getDb } from "@/db";
import { bookings } from "@/db/schema";
import { getBookingDetail } from "@/lib/domain/reservations";
import { getSessionUser } from "@/lib/auth";
import { formatFullDate, formatTime } from "@/lib/datetime";
import { formatInr, TRAVEL_CLASS_LABELS } from "@/lib/utils";
import { berthedLabel } from "@/lib/labels";
import { DemoCode } from "@/components/booking/demo-code";
import { Alert, Badge, DemoNotice, EmptyState, Panel } from "@/components/ui/surfaces";
import { Button } from "@/components/ui/button";

export const metadata: Metadata = { title: "Booking result" };
export const dynamic = "force-dynamic";

export default async function BookingResultPage({
  searchParams,
}: {
  searchParams: Promise<{ ref?: string }>;
}) {
  const session = await getSessionUser();
  const { ref } = await searchParams;
  if (!session) {
    redirect(`/login?next=${encodeURIComponent(`/booking/result?ref=${ref ?? ""}`)}`);
  }

  if (!ref) {
    return (
      <div className="mx-auto max-w-3xl px-4 py-16 sm:px-6">
        <EmptyState
          title="No booking reference supplied"
          description="Open a booking from My bookings to see its result and ticket."
          icon={<Ticket className="h-5 w-5" />}
        />
      </div>
    );
  }

  const [row] = await getDb()
    .select({ id: bookings.id })
    .from(bookings)
    .where(eq(bookings.reference, ref.toUpperCase()))
    .limit(1);

  if (!row) {
    return (
      <div className="mx-auto max-w-3xl px-4 py-16 sm:px-6">
        <EmptyState
          title="That reference was not found"
          description="Check the RAILVYN reference from your confirmation. References are generated by this demo and are not official PNRs."
          icon={<Ticket className="h-5 w-5" />}
        />
      </div>
    );
  }

  const detail = await getBookingDetail(row.id);
  if (detail.booking.userId !== session.id && !session.isAdmin && !session.isOperator) {
    redirect("/dashboard");
  }

  return (
    <div className="mx-auto max-w-4xl px-4 py-8 sm:px-6 lg:py-12">
      <div className="rounded-feature border border-success-ink/20 bg-success p-6 text-success-ink sm:p-8">
        <p className="flex items-center gap-2 text-xs font-semibold uppercase tracking-[0.12em]">
          <CheckCircle2 aria-hidden="true" className="h-4 w-4" />
          Demo booking confirmed
        </p>
        <div className="mt-3 flex flex-wrap items-end justify-between gap-4">
          <div>
            <h1 className="text-3xl font-semibold">You’re placed.</h1>
            <p className="mt-1 text-sm">
              {detail.train.name} · {formatFullDate(detail.run.departureAt)} ·{" "}
              {TRAVEL_CLASS_LABELS[detail.booking.travelClass]}
            </p>
          </div>
          <div className="rounded-small border border-success-ink/30 bg-white/40 px-4 py-2 text-right">
            <p className="text-[10px] font-semibold uppercase tracking-[0.1em]">
              RAILVYN reference
            </p>
            <p className="rv-mono mt-0.5 text-lg font-bold">{detail.booking.reference}</p>
          </div>
        </div>
        <p className="mt-4 max-w-2xl text-xs leading-relaxed">
          Keep this reference for your records. No ticket has been issued by Indian
          Railways, and nothing was charged to a real payment method.
        </p>
      </div>

      <div className="mt-5 grid gap-5 md:grid-cols-[1.3fr_1fr]">
        <Panel className="p-5 sm:p-6">
          <div className="flex items-center justify-between gap-2">
            <h2 className="text-lg font-semibold">Journey</h2>
            <Badge tone="success">Confirmed</Badge>
          </div>
          <div className="mt-4 flex flex-wrap items-end gap-4">
            <div>
              <p className="rv-mono text-2xl font-semibold">
                {formatTime(detail.run.departureAt)}
              </p>
              <p className="text-sm font-semibold">{detail.fromStop?.code}</p>
              <p className="text-xs text-ink-muted">{detail.fromStop?.name}</p>
            </div>
            <div className="text-ink-muted" aria-hidden="true">
              →
            </div>
            <div>
              <p className="text-sm font-semibold">{detail.toStop?.code}</p>
              <p className="text-xs text-ink-muted">{detail.toStop?.name}</p>
              <p className="mt-1 text-[10px] uppercase tracking-wide text-ink-muted">
                {TRAVEL_CLASS_LABELS[detail.booking.travelClass]}
              </p>
            </div>
          </div>

          <table className="mt-5 w-full text-left text-sm">
            <caption className="sr-only">Passengers and seats in this booking</caption>
            <thead className="text-[10px] uppercase tracking-[0.08em] text-ink-muted">
              <tr>
                <th scope="col" className="py-2">Passenger</th>
                <th scope="col" className="py-2">Seat</th>
                <th scope="col" className="py-2">Berth</th>
                <th scope="col" className="py-2 text-right">Fare</th>
              </tr>
            </thead>
            <tbody>
              {detail.seats.map((seat) => (
                <tr key={seat.bookingSeatId} className="border-t border-line-light/70">
                  <td className="py-2.5">
                    <span className="font-semibold">{seat.fullName}</span>
                    <span className="ml-2 text-xs text-ink-muted">
                      {seat.age} · {seat.gender}
                    </span>
                  </td>
                  <td className="rv-mono py-2.5">
                    {seat.coachCode} · {seat.seatNumber}
                  </td>
                  <td className="py-2.5 text-xs">{berthedLabel(seat.berthType)}</td>
                  <td className="rv-mono py-2.5 text-right">{formatInr(seat.farePaise)}</td>
                </tr>
              ))}
            </tbody>
          </table>

          <div className="mt-4 flex items-baseline justify-between border-t border-line-light pt-3">
            <span className="text-sm font-semibold">Total paid (demo)</span>
            <span className="rv-mono text-lg font-semibold">
              {formatInr(detail.booking.totalFarePaise)}
            </span>
          </div>

          <div className="mt-5 flex flex-wrap gap-2">
            <Button asChild>
              <Link href={`/my-bookings/${detail.booking.id}`}>
                <Ticket aria-hidden="true" className="h-4 w-4" />
                Open full ticket
              </Link>
            </Button>
            <Button asChild variant="outline">
              <Link href="/search">
                <Download aria-hidden="true" className="h-4 w-4" />
                Book another journey
              </Link>
            </Button>
          </div>
        </Panel>

        <div className="space-y-4">
          <Panel className="p-5 text-center">
            <DemoCode value={detail.booking.reference} className="mx-auto" />
            <p className="mt-3 text-[11px] leading-relaxed text-ink-muted">
              Demo code encodes only the internal reference. It cannot be used at
              any railway station.
            </p>
          </Panel>
          <Panel className="p-4">
            <Alert tone="warning" title="Payment status">
              Demo payment marked <strong>succeeded</strong>. No card detail was
              collected. Self-service cancellation is available until departure.
            </Alert>
            <DemoNotice className="mt-3" />
          </Panel>
        </div>
      </div>
    </div>
  );
}
