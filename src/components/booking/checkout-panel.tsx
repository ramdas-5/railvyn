"use client";

import { useActionState } from "react";
import { CreditCard, Lock, ShieldCheck } from "lucide-react";
import { confirmBookingAction } from "@/actions/booking";
import { IDLE_ACTION } from "@/lib/action-result";
import { SubmitButton } from "@/components/ui/submit-button";
import { Alert } from "@/components/ui/surfaces";
import { formatInr } from "@/lib/utils";

export function CheckoutPanel({
  holdId,
  idempotencyKey,
  totalFarePaise,
}: {
  holdId: string;
  idempotencyKey: string;
  totalFarePaise: number;
}) {
  const [state, formAction] = useActionState(confirmBookingAction, IDLE_ACTION);
  return (
    <form action={formAction} className="space-y-4">
      <input type="hidden" name="holdId" value={holdId} />
      <input type="hidden" name="idempotencyKey" value={idempotencyKey} />
      {state.status === "error" ? (
        <Alert tone="danger" title="Booking not confirmed">
          {state.message}
        </Alert>
      ) : null}
      <div className="rounded-small border border-warning-ink/25 bg-warning p-4 text-warning-ink">
        <p className="flex items-center gap-2 text-sm font-semibold">
          <CreditCard aria-hidden="true" className="h-4 w-4" />
          Demo payment · no card required
        </p>
        <p className="mt-1 text-xs leading-relaxed">
          This checkout simulates a successful payment of{" "}
          <strong>{formatInr(totalFarePaise)}</strong>. No payment gateway is
          contacted, no card data is requested or stored, and no real money moves.
        </p>
      </div>
      <label className="flex items-start gap-2.5 rounded-small border border-line-light bg-white/50 p-3 text-sm">
        <input
          type="checkbox"
          name="demoAcknowledged"
          required
          className="mt-0.5 h-4 w-4 rounded border-line-light accent-[#263416]"
        />
        <span>
          I understand this is a demonstration booking, not an official railway
          ticket, and that the reference is generated by RAILVYN.
        </span>
      </label>
      <SubmitButton className="w-full" pendingLabel="Confirming booking…">
        <Lock aria-hidden="true" className="h-4 w-4" />
        Pay {formatInr(totalFarePaise)} (demo) &amp; confirm
      </SubmitButton>
      <p className="flex items-center justify-center gap-1.5 text-[11px] text-ink-muted">
        <ShieldCheck aria-hidden="true" className="h-3.5 w-3.5" />
        Claims convert atomically. A booking cannot exist without its segments.
      </p>
    </form>
  );
}
